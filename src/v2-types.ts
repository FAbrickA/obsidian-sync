import type { Hash } from './types.ts';
export type { Hash } from './types.ts';
export type RevisionId = Hash;
export type EventId = Hash;
export const metadataDirV2 = '.webdav-sync-v2';
export const limitsV2 = { revisions: 256, parents: 256, events: 128, eventBytes: 1_048_576,
  containerBytes: 8_388_608, xmlBytes: 8_388_608, sealBytes: 4_194_304, segmentAttempts: 128,
  segmentEvents: 128, groupSegments: 128, mergeVariants: 32, mergeInputBytes: 1_000_000,
  mergeTotalBytes: 4_000_000, auditMs: 300_000, pollMs: 60_000, idleMs: 30_000, concurrency: 2 } as const;
export type V2Value = { kind: 'file'; path: string; hash: Hash; size: number } | { kind: 'tombstone'; path: string };
export type RevisionCore = { schema: 2; repositoryId: string; fileId: string; parents: RevisionId[]; value: V2Value;
  operation: 'create' | 'bootstrap' | 'edit' | 'rename' | 'delete' | 'merge' | 'resolve' | 'restore' | 'recreate';
  algorithmVersion: 1 | null; recreates: { oldFileId: string; tombstones: RevisionId[] } | null };
export type Revision = { id: RevisionId; core: RevisionCore };
export type SemanticEvent = { schema: 2; repositoryId: string; deviceId: string; operationId: string;
  previous: EventId | null; revisions: Revision[] };
export type EventRecord = { id: EventId; core: SemanticEvent };
export type ValidatedEvent = EventRecord;
export type SlotRef = { path: string; hash: Hash; size: number };
export type BlobRef = { hash: Hash; size: number; slot: SlotRef };
export type EventRef = { eventId: EventId; containerSlots: SlotRef[] };
export type RevisionSource = { revisionId: RevisionId; event: EventRef };
export type Container = { schema: 2; repositoryId: string; events: EventRecord[]; sources: BlobRef[];
  dependencies: RevisionSource[]; previousSources: EventRef[] };
export type IdentityRecord = { schema: 2; repositoryId: string };
export type SegmentRef = { deviceId: string; group: number; segmentId: string };
export type SealRecord = { schema: 2; repositoryId: string; segment: SegmentRef; members: EventRef[] };
export type SealProofV2 = {slot:SlotRef;record:SealRecord};
export type HintRecord = { schema: 2; repositoryId: string; deviceId: string; tip: EventRef | null };
export type IssueV2 = { kind: 'identity' | 'metadata' | 'source' | 'publication' | 'hint' | 'projection' | 'local';
  code: 'UnknownWrite' | 'Auth' | 'Network' | 'Quota' | 'Incomplete' | 'Corrupt' | 'Unsupported' | 'Collision' | 'IdentityChanged' | 'AdvisoryRepair'; relatedIds: string[] };
export type DecodedContainer = { hash: Hash; repositoryId: string; events: ValidatedEvent[]; sources: BlobRef[];
  dependencies: RevisionSource[]; previousSources: EventRef[]; issues: IssueV2[] };
export type AppliedFileV2 = { fileId: string; revisionIds: RevisionId[]; value: V2Value;
  baseHash: Hash | null; dirtyGeneration: number };
export type ConflictV2 = { id: Hash; fileId: string; variants: Revision[]; reason: string; baseCandidates: RevisionId[] };
export type PathConflictV2 = { id: Hash; paths: string[]; fileIds: string[]; reason: string };
export type CoverageV2 = { canonicalStarted: boolean; pendingEvents: EventId[]; pendingRevisions: RevisionId[]; issues: IssueV2[] };
export type RemoteViewV2 = { fingerprint: Hash; admittedEventIds: EventId[]; headsByFile: Record<string, Revision[]>;
  conflicts: ConflictV2[]; pathConflicts: PathConflictV2[]; pendingDependencies: RevisionId[];
  bodyStates: Record<Hash, 'unchecked' | 'verified' | 'missing' | 'corrupt'>; coverage: CoverageV2;
  pathHistory: Record<string, { fileId: string; revisionId: RevisionId; kind: 'file' | 'tombstone'; path: string }[]> };
export type CreationProofV2 = { path: string; generation: number; afterTombstone?: { oldFileId: string; tombstones: RevisionId[] } };
export type AdoptionPlanV2 = { adoptions: AppliedFileV2[]; branches: { fileId: string; path: string; operation: 'bootstrap'; parents: [] }[];
  births: { fileId: string; path: string; parents: []; operation: 'bootstrap' | 'create' | 'recreate'; recreates: RevisionCore['recreates'] }[];
  quarantined: { path: string; fileIds: string[]; reason: string }[] };
export type RunBoundaryV2 = { id: string; throughGeneration: number; admittedEventIds: EventId[] };
export type OperationFactsV2 = { publication: 'published' | 'not-required' | 'unknown'; localCheckpoint: boolean;
  issuedRequestsSettled: boolean; projectionSettled: boolean; conflictsPreserved: boolean };
export type RunOutcomeV2 = { state: 'clean' | 'conflicted' | 'pending' | 'blocked'; publishedEventIds: EventId[];
  localApplied: boolean; projectionChecked: boolean; pending: IssueV2[];
  boundaryCompletion: { id: string; acceptedOperationIds: string[]; admittedEventIds: EventId[];
    operations: Record<string, OperationFactsV2>; unresolvedAccepted: string[]; followUpRemote: boolean; advisoryPending: boolean } };
export type PublicationProofV2 = { eventId: EventId; container: SlotRef; blobs: BlobRef[] };
export type ApplyObligationV2 = { fileId: string; revisionIds: RevisionId[]; value: V2Value; applicationId: string;
  expected: import('./types.ts').LocalFile | null; prior: AppliedFileV2 | null; capturedLocal?: boolean; capturedGeneration?: number };
export type OutboxPhaseV2 = 'prepared' | 'uploading' | 'publication-unknown' | 'published' | 'applying' | 'completed' | 'cancelled-before-publication';
export type OutboxOperationV2 = { id: string; boundaryId: string; repositoryId: string; dirtyGeneration: number;
  event: EventRecord | null; pinnedHashes: Hash[]; apply: ApplyObligationV2[]; proof: PublicationProofV2 | null; phase: OutboxPhaseV2; conflictProofs?: Record<string, RevisionId[]> };
export type AttemptKindV2 = 'blob' | 'container' | 'seal' | 'identity' | 'archive';
export type AttemptRecordV2 = { attemptId: string; kind: AttemptKindV2; slot: SlotRef; bytes: ArrayBuffer; sessionId: string;
  segmentId?: string; logicalEventIds: EventId[]; state: 'planned' | 'issued' | 'settled-verified' | 'settled-unverified' };
export type FinalizeIntentV2 = { segmentId: string; ownerSessionId: string; allocatedEventIds: EventId[]; allocationClosed: true };
export type SegmentRecordV2 = SegmentRef & { repositoryId: string; ownerSessionId: string; attemptIds: string[];
  allocatedEventIds: EventId[]; retired: boolean; sealed: boolean; lastAllocationMs: number; finalization: FinalizeIntentV2 | null };
export type StoredContainerV2 = { slot: SlotRef; decoded: DecodedContainer };
export type ArchiveRefV2 = { id: Hash; path: string; hash: Hash; size: number; origin: 'local-quarantine' | 'projection-drift'; blob: BlobRef; slot: SlotRef };
export type ArchiveRecordV2 = Omit<ArchiveRefV2,'slot'> & {schema:2;repositoryId:string};
export type ProjectionResultV2 = { checkedFingerprint: Hash | null; pendingPaths: string[]; issues: IssueV2[]; followUpRemote: boolean };
export type ProjectionV2 = { materialize(view: RemoteViewV2, boundary: RunBoundaryV2, integrity?: boolean,verifiedBodies?:ReadonlySet<Hash>): Promise<ProjectionResultV2>;
  archiveUnknown(path: string, bytes: ArrayBuffer, origin: ArchiveRefV2['origin']): Promise<ArchiveRefV2>; archives(): Promise<ArchiveRefV2[]>;
  readCanonicalBytes?(revision:Revision):Promise<ArrayBuffer>;
  resolveDrift?(id:string,choice:'import-as-edit'|'repair-from-canonical'):Promise<{archive:ArchiveRefV2;bytes:ArrayBuffer}|null> };
